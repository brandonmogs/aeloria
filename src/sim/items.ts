/**
 * The item config registry — every item the game knows, keyed by id, in the
 * spirit of the obj configs an OSRS server ships. Instances in the world are
 * just `{ id, qty }` stacks ({@link ItemStack}); everything static lives here.
 *
 * Names, examine lines, values, weights, attack speeds, and the full stab /
 * slash / crush / magic / ranged bonus tables come straight from the OSRS
 * Wiki (src/sim/wikiItems.ts, generated by scripts/build-items.mjs). What an
 * item *does* in Aeloria — what it cooks into, which tool tier it is, what
 * level it needs — is defined here by hand.
 */

/** Equipment bonuses, in the order the OSRS equipment screen lists them. */
